import json,re
protos=json.load(open('gen/sdl_protos.json'))
# hand-written in sdl_special.c
SPECIAL={'SDL_GetWindowWMInfo','SDL_GetBasePath','SDL_RWFromFile','SDL_OpenAudioDevice','SDL_JoystickAttachVirtualEx','SDL_CreateWindow','SDL_RenderPresent','SDL_CreateRenderer'}
def split_top(s):
    out=[];d=0;cur=''
    for ch in s:
        if ch in '([': d+=1
        if ch in ')]': d-=1
        if ch==',' and d==0: out.append(cur.strip());cur=''
        else: cur+=ch
    if cur.strip(): out.append(cur.strip())
    return out
def ret_of(t):
    d=0
    for i,ch in enumerate(t):
        if ch=='(' and d==0: return t[:i].strip()
    raise Exception(t)
o=['/* generated by gen/gen_sdl.py -- typed Win64->SysV wrappers for SDL2 */',
   '#include "common.h"','#include <SDL.h>','#include <dlfcn.h>','']
tab=[]
for name,p in sorted(protos.items()):
    if name in SPECIAL: continue
    r=ret_of(p['type']); ps=p['params']
    if p.get('variadic'): print('variadic',name); continue
    if not ps or ps==['void']: ps=[]
    args=[];call=[]
    for i,t in enumerate(ps):
        args.append(f'{t} a{i}')
        if re.search(r'(Callback|Function)$',t.replace(' ','')): call.append(f'(void*)rev_thunk((void*)a{i})')
        else: call.append(f'a{i}')
    # function-pointer typed params need a cast
    call2=[]
    for i,t in enumerate(ps):
        if re.search(r'(Callback|Function)$',t.replace(' ','')): call2.append(f'({t})rev_thunk((void*)a{i})')
        else: call2.append(f'a{i}')
    # looked up lazily with dlsym: an SDL older than the headers (or an emulator's SDL bridge such as box64's) may lack a function; a missing one then returns 0 instead of aborting
    fail = 'return;' if r=='void' else f'return ({r}){{0}};'
    o.append(f'static MS {r} w_{name}({", ".join(args) or "void"}) {{ static __typeof__(&{name}) f; if (!f) f = (__typeof__(&{name}))dlsym(RTLD_DEFAULT, "{name}"); if (!f) {fail} {"return " if r!="void" else ""}f({", ".join(call2)}); }}')
    tab.append(name)
o.append('')
o.append('const struct import_entry sdl_generated_table[] = {')
for n in tab: o.append(f'  {{"{n}", (void*)w_{n}}},')
o.append('  {0,0}};')
open('src/sdl_wrap.c','w').write('\n'.join(o)+'\n')
print(len(tab),'wrappers')
